# --- Expression evaluator ----------------------------------------------------

def eval_expr(expr, lookup):
    """
    Evaluate a string like '2(26867) + 10544 + 2683 - 1' or
    '2(puzzle[15]) + 2683' using the current puzzles dict.
    """
    expr = expr.replace(" ", "")

    # Replace patterns like '2(26867)' -> '(2*26867)'
    expr = re.sub(r'(\d+)\(([^)]+)\)', r'(\1* (\2))', expr)

    # Replace puzzle references 'puzzleX' or 'kX' with value
    expr = re.sub(r'([pk]?)(\d+)', 
                  lambda m: str(lookup.get(int(m.group(2)), int(m.group(2)))), 
                  expr)

    try:
        return eval(expr)
    except Exception as e:
        print(f"Error evaluating: {expr}\n{e}")
        return None

