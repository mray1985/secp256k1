def oscillate(target, basis):
    remaining = target
    terms = []

    for g in basis:
        while remaining >= g:
            terms.append(g)
            remaining -= g
            if remaining >= 2 * g:
                terms.append(2 * g)
                remaining -= 2 * g
            else:
                break
        if remaining == 0:
            break

    return remaining, terms


def decompose(n):
    value = SEQ[n]
    g = SEQ[n - 3]

    m, r = divmod(value, g)

    # Step 1: build m * g by oscillation
    main_target = m * g
    _, main_terms = oscillate(main_target, [g])

    # Step 2: decompose remainder
    basis = sorted([SEQ[i] for i in range(1, n - 3)], reverse=True)
    rem, rem_terms = oscillate(r, basis)

    return rem, main_terms + rem_terms


